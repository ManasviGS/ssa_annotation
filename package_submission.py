#!/usr/bin/env python3
"""Build the submission ZIP from a finished `annotate.py run` output folder.

Usage:
  python package_submission.py results/ --report report.pdf --out digantara_submission.zip \
         [--repo-url https://github.com/<you>/<repo>] [--include-raw16] [--include-repatched16] [--skip-validate]

Steps: (1) validate the YOLO export, (2) make the repatched full-size images if missing,
(3) count objects per frame from the *_meta.json files, (4) write the ZIP + access instructions.
Default ZIP = code + report + YOLO dataset (8-bit tiles + labels + pixel masks + manifest) + full-size overlays + repatched 8-bit mosaics.
Optional (large): --include-raw16 (lossless 16-bit tiles), --include-repatched16 (lossless 16-bit mosaics).
"""
import argparse
import glob
import json
import os
import subprocess
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
CODE_FILES = ["annotate.py", "diagnose.py", "validate_dataset.py", "make_masks.py", "package_submission.py", "make_synthetic.py",
              "evaluate_synthetic.py", "requirements.txt", "README.md", ".gitignore"]


def counts_table(out_dir):
    rows = []
    for mp in sorted(glob.glob(os.path.join(out_dir, "full", "*_meta.json"))):
        d = json.load(open(mp))
        objs = d["objects"]
        ns = sum(o["cls"] == "star" for o in objs)
        nk = sum(o["cls"] == "streak" for o in objs)
        rows.append((d["meta"]["stem"], d["meta"]["width"], d["meta"]["height"], ns, nk))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("--report", default=os.path.join(HERE, "report.pdf"))
    ap.add_argument("--out", default="digantara_submission.zip")
    ap.add_argument("--repo-url", default="")
    ap.add_argument("--include-raw16", action="store_true")
    ap.add_argument("--include-repatched16", action="store_true")
    ap.add_argument("--skip-validate", action="store_true")
    a = ap.parse_args()
    d = a.out_dir.rstrip("/\\")

    if not a.skip_validate:
        r = subprocess.run([sys.executable, os.path.join(HERE, "validate_dataset.py"), d])
        if r.returncode:
            sys.exit("validation failed - fix the problems above (or --skip-validate) before packaging")

    r = subprocess.run([sys.executable, os.path.join(HERE, "make_masks.py"), d])
    if r.returncode:
        sys.exit("mask/manifest check failed - fix the problems above before packaging")
    masks_exact = not os.path.exists(os.path.join(d, "masks", "FROM_POLYGONS.txt"))

    rows = counts_table(d)
    if not rows:
        sys.exit(f"no *_meta.json in {d}/full - has `annotate.py run` finished for any frame?")
    missing = [s for s, *_ in rows if not os.path.exists(os.path.join(d, "full", s + "_repatched8.png"))]
    if missing:
        print(f"making repatched mosaics for {len(missing)} frame(s) ...")
        sys.path.insert(0, HERE)
        import annotate
        annotate.repatch(d)

    table = ["| Frame | Size | Stars | Streaks |", "|---|---|---|---|"]
    table += [f"| {s} | {w}x{h} | {ns} | {nk} |" for s, w, h, ns, nk in rows]
    table.append(f"| **Total ({len(rows)} frames)** | | **{sum(r[3] for r in rows)}** | **{sum(r[4] for r in rows)}** |")
    table_txt = "\n".join(table)
    print("\n" + table_txt + "\n")

    instr = f"""DIGANTARA ASSESSMENT - SSA STAR/STREAK ANNOTATION - HOW TO USE THIS ZIP
=====================================================================
Unzip, then open the folders below. Nothing needs to be installed just to look at the results.

report/report.pdf         Written response (Q2 a-d), max. 4 pages.
dataset/                  YOLO-Ultralytics SEGMENTATION dataset, 1024x1024 tiles
  images/<frame>_r<row>_c<col>.png    8-bit asinh-stretched tiles (detection is done on the 16-bit data, not on these)
  labels/<frame>_r<row>_c<col>.txt    one line per object: `class x1 y1 x2 y2 ...` (polygon, normalised 0..1)
                                      class 0 = star/blob, class 1 = streak/space object
  masks/<frame>_r<row>_c<col>.png     pixel-level mask of the same tile, uint8: 0 = background, 1 = star/blob, 2 = streak
{"                                      (exact detection mask; every pixel has one label, classes never overlap)" if masks_exact else "                                      (rasterised from the polygons: approximate; holes filled, overlaps -> streak)"}
  manifest.csv                        one row per tile: source frame, row/col, pixel box in the source frame, padding, counts, file paths
  dataset.yaml                        Ultralytics dataset file (classes 0: star, 1: streak)
{"  tiles_raw16/                        lossless 16-bit tiles of the raw FITS data" if a.include_raw16 else "  (16-bit tiles are not included to keep the ZIP small; they are regenerated by the code)"}
outputs/                  Full-size (9568x6380) imagery for visual inspection
  <frame>_overlay.png                 stretched frame with masks (blue = star, red = streak)
  <frame>_repatched8.png              the 1024x1024 tiles stitched back together, padding removed
{"  <frame>_repatched16.png             lossless 16-bit mosaic of the raw data (equals the FITS data exactly)" if a.include_repatched16 else ""}
  <frame>_meta.json                   per-object catalogue (class, centroid, area, length, aspect, peak SNR) + config
  object_counts.md                    object counts per frame
code/                     the full pipeline (also at: {a.repo_url or "<add GitHub link here>"})

Tip: the overlay/mosaic PNGs are about 61 megapixels; open them in an image viewer that can zoom
(e.g. IrfanView, GIMP, Photos) and look at the 1024x1024 tiles in dataset/images for detail.

Re-running the pipeline (Python 3.9+):
  cd code && pip install -r requirements.txt
  python annotate.py run <folder with the 10 FITS files> results --snr-high 6
  python annotate.py repatch results --fits-dir <folder with the FITS files>   # stitched tiles == FITS data check
  python validate_dataset.py results                                          # checks every label file
  python -m pytest tests -q
Using the labels (no model has been trained as part of this submission):
  yolo segment train data=dataset/dataset.yaml model=yolo11n-seg.pt imgsz=1024
Reviewing/correcting in CVAT: import dataset/images + dataset/labels as "Ultralytics YOLO Segmentation 1.0".

Object counts (automatic detections, before manual review):
{table_txt}
"""
    with zipfile.ZipFile(a.out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("README_ACCESS.txt", instr)
        z.writestr("outputs/object_counts.md", table_txt + "\n")
        if os.path.exists(a.report):
            z.write(a.report, "report/" + os.path.basename(a.report))
            docx = os.path.splitext(a.report)[0] + ".docx"
            if os.path.exists(docx):
                z.write(docx, "report/" + os.path.basename(docx))
        else:
            print(f"WARNING: report not found at {a.report}")
        for f in CODE_FILES:
            if os.path.exists(os.path.join(HERE, f)):
                z.write(os.path.join(HERE, f), "code/" + f)
        for f in glob.glob(os.path.join(HERE, "tests", "*.py")):
            z.write(f, "code/tests/" + os.path.basename(f))
        if os.path.exists(os.path.join(d, "manifest.csv")):
            z.write(os.path.join(d, "manifest.csv"), "dataset/manifest.csv")
        for sub in ("images", "labels", "masks") + (("tiles_raw16",) if a.include_raw16 else ()):
            for f in sorted(glob.glob(os.path.join(d, sub, "*"))):
                if os.path.basename(f) == "FROM_POLYGONS.txt":
                    continue
                z.write(f, f"dataset/{sub}/" + os.path.basename(f))
        if os.path.exists(os.path.join(d, "dataset.yaml")):
            z.write(os.path.join(d, "dataset.yaml"), "dataset/dataset.yaml")
        pats = ["*_overlay.png", "*_repatched8.png", "*_meta.json"] + (["*_repatched16.png"] if a.include_repatched16 else [])
        for p in pats:
            for f in sorted(glob.glob(os.path.join(d, "full", p))):
                z.write(f, "outputs/" + os.path.basename(f))
    print(f"wrote {a.out}  ({os.path.getsize(a.out) / 1e6:.0f} MB)")


if __name__ == "__main__":
    main()
